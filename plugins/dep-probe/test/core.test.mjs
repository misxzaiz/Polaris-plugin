// ── severity / 归并 / 忽略 / 修复方案 ───────────────────────────────────────

const V = {
  ghsaHigh: { id: 'GHSA-h', summary: 'x', database_specific: { severity: 'HIGH' }, affected: [{ ranges: [{ events: [{ introduced: '0' }, { fixed: '4.17.19' }] }] }] },
  ghsaCritical: { id: 'GHSA-c', database_specific: { severity: 'CRITICAL' }, affected: [{ ranges: [{ events: [{ fixed: '2.0.0' }] }] }] },
  numeric: { id: 'CVE-n', severity: [{ score: 7.5 }], affected: [{ ranges: [{ events: [{ fixed: '3.1.0' }] }] }] },
  vectorOnly: { id: 'CVE-v', severity: [{ type: 'CVSS_V3', score: 'CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H' }], affected: [] },
  noFix: { id: 'RUSTSEC-nofix', database_specific: { severity: 'LOW' }, affected: [{ ranges: [{ events: [{ introduced: '0' }] }] }] },
}

test('severityOf：GHSA 标签 / 数值分桶 / 纯向量=未分级', () => {
  assert.equal(core.severityOf(V.ghsaHigh), 'high')
  assert.equal(core.severityOf(V.ghsaCritical), 'critical')
  assert.equal(core.severityOf(V.numeric), 'high')
  assert.equal(core.severityOf(V.vectorOnly), 'unknown')
  assert.equal(core.severityOf(null), 'unknown')
})

test('collectFindings：详情缺失降级（detailOk=false）+ 排序按严重度', () => {
  const pkgs = [
    { name: 'lodash', version: '4.17.15', ecosystem: 'npm', file: 'a', repoDir: 'r1' },
    { name: 'serde', version: '1.0.100', ecosystem: 'crates.io', file: 'b', repoDir: 'r2' },
    { name: 'clean', version: '1.0.0', ecosystem: 'npm', file: 'a', repoDir: 'r1' },
  ]
  const results = [{ vulns: [{ id: 'GHSA-h' }, { id: 'CVE-n' }] }, { vulns: [{ id: 'GHSA-c' }] }, {}]
  const detailMap = new Map([['GHSA-h', V.ghsaHigh], ['GHSA-c', V.ghsaCritical]]) // CVE-n 无详情
  const fs2 = core.collectFindings(pkgs, results, detailMap)
  assert.equal(fs2.length, 3)
  assert.equal(fs2[0].severity, 'critical') // 排序首位
  const noDetail = fs2.find((f) => f.vulnId === 'CVE-n')
  assert.equal(noDetail.detailOk, false)
  assert.equal(noDetail.severity, 'unknown')
})

test('applyIgnores：pkg+vulnId 命中；空规则（无锚点）不吞任何发现', () => {
  const findings = [
    { pkg: 'lodash', version: '4.17.15', ecosystem: 'npm', vulnId: 'GHSA-h', severity: 'high', fixed: ['4.17.19'], aliases: [], summary: '' },
    { pkg: 'serde', version: '1.0.100', ecosystem: 'crates.io', vulnId: 'GHSA-c', severity: 'critical', fixed: ['2.0.0'], aliases: [], summary: '' },
  ]
  const r1 = core.applyIgnores(findings, [{ pkg: 'lodash', vulnId: 'GHSA-h', reason: '误报' }])
  assert.equal(r1.findings.length, 1)
  assert.equal(r1.ignoredCount, 1)
  assert.equal(r1.findings[0].pkg, 'serde')
  const r2 = core.applyIgnores(findings, [{ reason: '坏规则：无锚点' }])
  assert.equal(r2.findings.length, 2)
  const r3 = core.applyIgnores(findings, [{ pkg: 'lodash' }]) // 只锚 pkg：整包忽略
  assert.deepEqual(r3.findings.map((f) => f.pkg), ['serde'])
})

test('buildFixPlan：跨漏洞取 max fixed + 严重度归并 + 无修复版本如实呈现', () => {
  const findings = [
    { pkg: 'lodash', version: '4.17.15', ecosystem: 'npm', vulnId: 'GHSA-h', severity: 'high', fixed: ['4.17.19'], aliases: [], summary: '' },
    { pkg: 'lodash', version: '4.17.15', ecosystem: 'npm', vulnId: 'GHSA-h2', severity: 'critical', fixed: ['4.17.21'], aliases: [], summary: '' },
    { pkg: 'stuck', version: '1.0.0', ecosystem: 'crates.io', vulnId: 'RUSTSEC-nofix', severity: 'low', fixed: [], aliases: [], summary: '' },
  ]
  const plan = core.buildFixPlan(findings)
  assert.equal(plan.length, 2)
  const lodash = plan.find((p) => p.pkg === 'lodash')
  assert.equal(lodash.to, '4.17.21') // 两个漏洞的 max fixed
  assert.equal(lodash.severity, 'critical') // 取最高严重度
  assert.equal(lodash.vulnIds.length, 2)
  const stuck = plan.find((p) => p.pkg === 'stuck')
  assert.equal(stuck.to, null)
})

